namespace Threadforge.Threadlink.Generators
{
    using System.Collections.Generic;
    using System.Collections.Immutable;
    using System.Linq;
    using System.Text;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp.Syntax;

    /// <summary>
    /// Registers every concrete Threadlink subsystem of an assembly at RuntimeInitializeLoadType.SubsystemRegistration.
    /// A subsystem is a non-abstract class deriving from Threadforge.Threadlink.Subsystem&lt;TSelf&gt; with TSelf being the
    /// class itself, a public parameterless constructor and no [ManualRegistration].
    /// </summary>
    [Generator]
    public sealed class SubsystemRegistrationGenerator : IIncrementalGenerator
    {
        private const string SubsystemBase = "Threadforge.Threadlink.ThreadlinkSubsystem<TSelf>";
        private const string ManualRegistration = "Threadforge.Threadlink.ManualRegistrationAttribute";

        private static readonly DiagnosticDescriptor Inaccessible = new DiagnosticDescriptor(
            "TL0001",
            "ThreadlinkSubsystem cannot be registered",
            "ThreadlinkSubsystem '{0}' is not registered automatically: {1}. Fix it or mark it [ManualRegistration].",
            "Threadlink",
            DiagnosticSeverity.Warning,
            true
        );

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var candidates = context
                .SyntaxProvider.CreateSyntaxProvider(
                    static (node, _) => node is ClassDeclarationSyntax declaration && declaration.BaseList != null,
                    static (syntax, token) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, token) as INamedTypeSymbol
                )
                .Where(static symbol => symbol != null);
            context.RegisterSourceOutput(context.CompilationProvider.Combine(candidates.Collect()), static (output, input) => Emit(output, input.Left, input.Right));
        }

        private static void Emit(SourceProductionContext output, Compilation compilation, ImmutableArray<INamedTypeSymbol> candidates)
        {
            var registered = new List<string>();
            var seen = new HashSet<string>();
            foreach (var type in candidates)
            {
                string name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (!seen.Add(name) || type.IsAbstract || type.TypeKind != TypeKind.Class || !IsSubsystem(type))
                    continue;
                if (type.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == ManualRegistration))
                    continue;
                string problem = Problem(type);
                if (problem != null)
                {
                    output.ReportDiagnostic(Diagnostic.Create(Inaccessible, type.Locations.FirstOrDefault(), type.Name, problem));
                    continue;
                }
                registered.Add(name);
            }
            if (registered.Count == 0)
                return;
            registered.Sort(System.StringComparer.Ordinal);
            var code = new StringBuilder();
            code.AppendLine("// <auto-generated>Threadlink subsystem registration.</auto-generated>");
            code.AppendLine("namespace Threadforge.Threadlink.Generated");
            code.AppendLine("{");
            code.Append("    internal static class SubsystemRegistration_").AppendLine(Identifier(compilation.AssemblyName));
            code.AppendLine("    {");
            code.AppendLine("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            code.AppendLine("        private static void Register()");
            code.AppendLine("        {");
            foreach (string name in registered)
                code.Append("            global::Threadforge.Threadlink.Threadlink.Register<").Append(name).AppendLine(">();");
            code.AppendLine("        }");
            code.AppendLine("    }");
            code.AppendLine("}");
            output.AddSource("ThreadlinkSubsystemRegistration.g.cs", code.ToString());
        }

        private static bool IsSubsystem(INamedTypeSymbol type)
        {
            for (var current = type.BaseType; current != null; current = current.BaseType)
                if (current.IsGenericType && current.OriginalDefinition.ToDisplayString() == SubsystemBase)
                    return SymbolEqualityComparer.Default.Equals(current.TypeArguments[0], type);
            return false;
        }

        private static string Problem(INamedTypeSymbol type)
        {
            if (type.IsGenericType)
                return "generic subsystems need explicit registration";
            for (var current = type; current != null; current = current.ContainingType)
                if (current.DeclaredAccessibility == Accessibility.Private || current.DeclaredAccessibility == Accessibility.Protected || current.DeclaredAccessibility == Accessibility.ProtectedAndInternal)
                    return "it is not accessible from its assembly";
            if (!type.InstanceConstructors.Any(constructor => constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility == Accessibility.Public))
                return "it has no public parameterless constructor";
            return null;
        }

        private static string Identifier(string assembly)
        {
            var text = new StringBuilder();
            foreach (char character in assembly ?? "Assembly")
                text.Append(char.IsLetterOrDigit(character) ? character : '_');
            return text.ToString();
        }
    }
}
